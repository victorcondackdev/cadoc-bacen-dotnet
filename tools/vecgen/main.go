// Command vecgen generates the cross-language parity vectors used by the C#
// test suite from the Go implementation (github.com/victorcondackdev/cadoc-bacen-go):
// Cosif codes, trial balances and their 4010/4016 XML, validation findings,
// deadlines, SCR buckets and 3040 documents.
//
// Usage, from the repository root, with the Go module cloned next to it:
//
//	go -C tools/vecgen run . > tests/CadocBacen.Tests/Parity/GoVectors.g.cs
package main

import (
	"bytes"
	"fmt"
	"math/rand"
	"os"
	"sort"
	"strconv"
	"strings"

	"github.com/victorcondackdev/cadoc-bacen-go/balancete"
	"github.com/victorcondackdev/cadoc-bacen-go/bizday"
	"github.com/victorcondackdev/cadoc-bacen-go/cosif"
	"github.com/victorcondackdev/cadoc-bacen-go/doc3040"
	"github.com/victorcondackdev/cadoc-bacen-go/doc4010"
)

var rng = rand.New(rand.NewSource(20261127))

func lit(s string) string { return `@"` + strings.ReplaceAll(s, `"`, `""`) + `"` }
func q(s string) string   { return strconv.Quote(s) }

func digits(n int) string {
	var b strings.Builder
	for i := 0; i < n; i++ {
		b.WriteByte(byte('0' + rng.Intn(10)))
	}
	return b.String()
}

func cpf() string {
	for {
		s := digits(9)
		for k := 0; k < 100; k++ {
			c := s + fmt.Sprintf("%02d", k)
			if doc3040.ValidCPF(c) {
				return c
			}
		}
	}
}

func cnpj() string {
	for {
		s := digits(8) + "0001"
		for k := 0; k < 100; k++ {
			c := s + fmt.Sprintf("%02d", k)
			if doc3040.ValidCNPJ(c) {
				return c
			}
		}
	}
}

func encodeLeaves(m map[cosif.Code]balancete.Money) string {
	var parts []string
	for c, v := range m {
		parts = append(parts, fmt.Sprintf("%s=%d", c.Compact(), v))
	}
	sort.Strings(parts)
	return strings.Join(parts, ";")
}

func main() {
	var o bytes.Buffer
	p := func(f string, a ...any) { fmt.Fprintf(&o, f, a...) }
	p("// <auto-generated>\n// Generated by tools/vecgen from the Go implementation (github.com/victorcondackdev/cadoc-bacen-go).\n")
	p("// Do not edit by hand; regenerate with: go -C tools/vecgen run . > tests/CadocBacen.Tests/Parity/GoVectors.g.cs\n// </auto-generated>\n\n")
	p("namespace CadocBacen.Tests.Parity;\n\ninternal static class GoVectors\n{\n")

	p("    public static readonly (string Body, string Dotted, string Compact, int Level, string Parent)[] Codes =\n    {\n")
	for i := 0; i < 200; i++ {
		body := digits(1 + rng.Intn(9))
		body += strings.Repeat("0", 9-len(body))
		if body[0] == '0' {
			body = "1" + body[1:]
		}
		c := cosif.MustParse(body)
		parent := ""
		if pc, ok := c.Parent(); ok {
			parent = pc.Compact()
		}
		p("        (%q, %q, %q, %d, %q),\n", body, c.String(), c.Compact(), c.Level(), parent)
	}
	p("    };\n\n")

	chart := cosif.SampleChart()
	var leaves, debits, credits []cosif.Code // non-memorandum leaves, by nature
	for _, a := range chart.Accounts() {
		if chart.IsLeaf(a.Code) && a.Code.Group() != 3 && a.Code.Group() != 9 {
			leaves = append(leaves, a.Code)
			if a.Nature() == cosif.Debit {
				debits = append(debits, a.Code)
			} else {
				credits = append(credits, a.Code)
			}
		}
	}
	// pair picks a debit and a credit leaf; one time in five, any two.
	pair := func() (cosif.Code, cosif.Code) {
		if rng.Intn(5) == 0 {
			return leaves[rng.Intn(len(leaves))], leaves[rng.Intn(len(leaves))]
		}
		return debits[rng.Intn(len(debits))], credits[rng.Intn(len(credits))]
	}
	memo := func(m map[cosif.Code]balancete.Money) {
		if rng.Intn(2) == 0 {
			v := balancete.Money(rng.Int63n(900_000_00))
			m[cosif.MustParse("310000000")] += v
			m[cosif.MustParse("910000000")] -= v
		}
	}
	p("    public static readonly (string Leaves, string Issues, string Xml4010, string Xml4016, string Closed)[] Balances =\n    {\n")
	for i := 0; i < 40; i++ {
		m := map[cosif.Code]balancete.Money{}
		for k := 0; k < 3+rng.Intn(12); k++ {
			a, b := pair()
			v := balancete.Money(rng.Int63n(5_000_000_00))
			m[a] += v
			m[b] -= v
		}
		memo(m)
		switch i % 8 {
		case 6:
			m[leaves[rng.Intn(len(leaves))]] += balancete.Money(rng.Intn(1000) + 1)
		case 7:
			m[cosif.MustParse("310000000")] += 1
		}
		b, err := balancete.FromLeaves(chart, m)
		if err != nil {
			panic(err)
		}
		var issues []string
		for _, is := range b.Check() {
			issues = append(issues, is.String())
		}
		x10, x16, closedXML := "", "", ""
		if d, err := doc4010.Build(doc4010.Balancete, "12345678", "2026-10", doc4010.Inclusion, b, doc4010.Options{IncludeZero: i%3 == 0}); err == nil {
			x10 = string(d.Marshal())
		} else {
			x10 = "ERR " + err.Error()
		}
		closed, _ := b.CloseResult(cosif.MustParse("641000000"), cosif.MustParse("649000000"))
		if d, err := doc4010.Build(doc4010.Balanco, "12345678", "2026-12", doc4010.Substitution, closed, doc4010.Options{}); err == nil {
			x16 = string(d.Marshal())
		} else {
			x16 = "ERR " + err.Error()
		}
		if d, err := doc4010.Build(doc4010.Balanco, "12345678", "2026-06", doc4010.Inclusion, b, doc4010.Options{}); err != nil {
			closedXML = "ERR " + err.Error()
		} else {
			closedXML = string(d.Marshal())
		}
		p("        (%q, %s, %s, %s, %s),\n", encodeLeaves(m), lit(strings.Join(issues, "\n")), lit(x10), lit(x16), lit(closedXML))
	}
	p("    };\n\n")

	// Tampered documents: change one saldo, validate against the chart.
	p("    public static readonly (string Xml, string Problems)[] Tampered =\n    {\n")
	for i := 0; i < 20; i++ {
		m := map[cosif.Code]balancete.Money{}
		for k := 0; k < 6; k++ {
			a, b := pair()
			v := balancete.Money(rng.Int63n(1_000_000_00))
			m[a] += v
			m[b] -= v
		}
		memo(m)
		b, _ := balancete.FromLeaves(chart, m)
		d, err := doc4010.Build(doc4010.Balancete, "12345678", "2026-10", doc4010.Inclusion, b, doc4010.Options{})
		if err != nil || len(d.Lines) == 0 {
			continue
		}
		k := rng.Intn(len(d.Lines))
		switch rng.Intn(3) {
		case 0:
			d.Lines[k].Saldo += balancete.Money(1 + rng.Intn(500))
		case 1:
			d.Lines = append(d.Lines[:k], d.Lines[k+1:]...)
		default:
			d.Lines = append(d.Lines, doc4010.Line{Code: cosif.MustParse("150000000"), Saldo: 1})
		}
		p("        (%s, %s),\n", lit(string(d.Marshal())), lit(strings.Join(d.Validate(chart), "\n")))
	}
	p("    };\n\n")

	p("    public static readonly (string DataBase, string Deadline4010, string Deadline4016)[] Deadlines =\n    {\n")
	for y := 2024; y <= 2031; y++ {
		for m := 1; m <= 12; m++ {
			base := fmt.Sprintf("%04d-%02d", y, m)
			d10, _ := doc4010.Deadline(doc4010.Balancete, base, nil)
			d16 := ""
			if m == 6 || m == 12 {
				x, _ := doc4010.Deadline(doc4010.Balanco, base, nil)
				d16 = x.String()
			}
			p("        (%q, %q, %q),\n", base, d10.String(), d16)
		}
	}
	p("    };\n\n")

	p("    public static readonly (string Reference, string Due, int Bucket, int WriteOff)[] Buckets =\n    {\n")
	for i := 0; i < 300; i++ {
		ref := bizday.MustParse("2025-01-31").AddDays(rng.Intn(800))
		ref = bizday.LastOfMonth(ref)
		var due bizday.Date
		switch rng.Intn(3) {
		case 0:
			due = ref.AddDays(rng.Intn(60) - 30)
		case 1:
			due = ref.AddDays(rng.Intn(1400) - 700)
		default:
			due = ref.AddDays(rng.Intn(12000) - 3000)
		}
		p("        (%q, %q, %d, %d),\n", ref.String(), due.String(), doc3040.BucketFor(ref, due), doc3040.WriteOffBucket(ref, due))
	}
	p("    };\n\n")

	p("    public static readonly (string Clients, string Xml)[] Scr =\n    {\n")
	for i := 0; i < 15; i++ {
		h := doc3040.Header{CNPJ: "12345678", DataBase: fmt.Sprintf("2026-%02d", 1+rng.Intn(12)), Remessa: 1 + rng.Intn(2), Parte: 1,
			NomeResp: "Resp & Cia", EmailResp: "scr@banco.example", TelResp: "2133334444"}
		var clients []doc3040.Client
		var enc []string
		for c := 0; c < 1+rng.Intn(4); c++ {
			cl := doc3040.Client{Type: 1 + rng.Intn(2), Authorized: rng.Intn(2) == 0, Since: bizday.MustParse("2020-01-01").AddDays(rng.Intn(2000)),
				Income: balancete.Money(1000_00 + rng.Int63n(5_000_000_00))}
			if cl.Type == 1 {
				cl.Document, cl.Size = cpf(), 1+rng.Intn(8)
			} else {
				cl.Document, cl.Size = cnpj(), 1+rng.Intn(4)
			}
			ce := []string{fmt.Sprintf("%d|%s|%t|%d|%s|%d", cl.Type, cl.Document, cl.Authorized, cl.Size, cl.Since, cl.Income)}
			for k := 0; k < 1+rng.Intn(3); k++ {
				op := doc3040.Operation{Contract: fmt.Sprintf("CT-%d-%d-%d", i, c, k), Modality: []string{"0202", "0203", "0216", "0401", "0101"}[rng.Intn(5)],
					CEP: digits(8), Rate: fmt.Sprintf("%d.%02d", rng.Intn(150), rng.Intn(100)), Contracted: bizday.MustParse("2024-01-01").AddDays(rng.Intn(700)),
					Value: balancete.Money(rng.Int63n(100_000_00) + 100_00), Provision: balancete.Money(rng.Int63n(5_000_00))}
				if rng.Intn(3) == 0 {
					op.Special = []string{"1", "18"}[:1+rng.Intn(2)]
				}
				first := bizday.MustParse("2024-06-01").AddDays(rng.Intn(900))
				var inst []string
				for n := 0; n < 1+rng.Intn(24); n++ {
					it := doc3040.Installment{Due: first.AddDays(30 * n), Amount: balancete.Money(rng.Int63n(5_000_00) + 1)}
					op.Installments = append(op.Installments, it)
					inst = append(inst, fmt.Sprintf("%s=%d", it.Due, it.Amount))
				}
				wo := ""
				if rng.Intn(6) == 0 {
					op.WrittenOff = bizday.MustParse("2022-01-15").AddDays(rng.Intn(1500))
					wo = op.WrittenOff.String()
				}
				ce = append(ce, fmt.Sprintf("%s|%s|%s|%s|%s|%d|%d|%s|%s|%s", op.Contract, op.Modality, op.CEP, op.Rate, op.Contracted, op.Value, op.Provision,
					strings.Join(op.Special, ","), wo, strings.Join(inst, ",")))
				cl.Operations = append(cl.Operations, op)
			}
			clients = append(clients, cl)
			enc = append(enc, strings.Join(ce, "\n"))
		}
		header := fmt.Sprintf("%s|%s|%d|%d|%s|%s|%s", h.CNPJ, h.DataBase, h.Remessa, h.Parte, h.NomeResp, h.EmailResp, h.TelResp)
		out, err := doc3040.Build(h, clients)
		x := string(out)
		if err != nil {
			x = "ERR " + err.Error()
		}
		p("        (%s, %s),\n", lit(header+"\n#\n"+strings.Join(enc, "\n#\n")), lit(x))
	}
	p("    };\n}\n")
	_ = q
	os.Stdout.Write(o.Bytes())
}
